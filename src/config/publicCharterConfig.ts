export function validateCharterCompleteness(): { complete: boolean; missing: string[] } {
  const required = ['purpose', 'whatPlatformDoes', 'whatPlatformDoesNot', 'neutralityMethod', 'userResponsibility', 'corePrinciple'];
  const present = Object.keys(PUBLIC_CHARTER).filter(k => !['version', 'effectiveDate', 'title'].includes(k));
  const missing = required.filter(r => !present.includes(r));
  return { complete: missing.length === 0, missing };
}

export function validateToSCompleteness(): { complete: boolean; clauseCount: number } {
  return {
    complete: TERMS_OF_SERVICE.clauses.length >= 6,
    clauseCount: TERMS_OF_SERVICE.clauses.length,
  };
}
